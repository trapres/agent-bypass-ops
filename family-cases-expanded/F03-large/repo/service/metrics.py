def format_bucket_000(values: Iterable[float]) -> str:
    """Render latency bucket 000 as a fixed-width row."""
    items = sorted(float(v) for v in values)
    if not items:
        return "-"
    return "{:>9.3f} {:>9.3f} {:>6d}".format(items[0], items[-1], len(items))


